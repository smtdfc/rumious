import {
  compile,
  CompileOption,
  generate_router_decl_code,
} from "@rumious/compiler";
import type { Plugin } from "vite";
import glob from "fast-glob";
import path from "path";
import { createJiti } from "jiti";
import type { Config } from "@rumious/config";
import fs from "fs/promises";

async function loadConfig(): Promise<Config> {
  const jiti = createJiti(import.meta.url);
  const configPath = path.resolve(process.cwd(), "rumious.config.ts");

  try {
    const module = await jiti.import(configPath, { default: true });
    return module || {};
  } catch (e) {
    console.warn("[Rumious] No rumious.config.ts found, using defaults.");
    return {};
  }
}
const getCleanPath = (filePath: string, config: Config) => {
  // 1. Xác định thư mục gốc tuyệt đối (Absolute Root)
  const root = path.resolve(config.root || process.cwd());

  // 2. Xác định thư mục routes tuyệt đối
  const routesDirRelative = (config.routesDir || "src/routes").replace(
    /\/\*\*.*$/,
    "",
  );
  const absoluteRoutesDir = path.resolve(root, routesDirRelative);

  // 3. Chuyển filePath về tuyệt đối để đảm bảo cùng hệ quy chiếu
  const absoluteFilePath = path.resolve(filePath);

  // 4. Lấy phần đường dẫn tương đối từ absoluteRoutesDir đến file
  // Ví dụ: Từ 'D:/.../src/routes' đến 'D:/.../src/routes/index.page.ts'
  // sẽ ra 'index.page.ts'
  let relativePath = path.relative(absoluteRoutesDir, absoluteFilePath);

  // 5. Chuẩn hóa dấu gạch chéo (đề phòng Windows dùng \) và thêm / ở đầu
  relativePath = relativePath.replace(/\\/g, "/");

  return relativePath.startsWith("/") ? relativePath : "/" + relativePath;
};
export default async function vitePluginRumious(): Promise<Plugin<any>> {
  const config = await loadConfig();
  const VIRTUAL_MODULE_ID = "virtual:rumious-router";
  const RESOLVED_VIRTUAL_MODULE_ID = "\0" + VIRTUAL_MODULE_ID;
  const root = (config.root || process.cwd()).replace(/\\/g, "/");
  const pattern = (config.routesDir || "routes") + "/**/*.{ts,tsx,js,jsx}";
  const ROUTES_DIR = `${root}/${pattern}`;
  let routeDeclCode = "export const routes = [];";

  const refreshRouter = async (server?: any) => {
    try {
      const files = await glob(pattern, {
        cwd: root,
        absolute: true,
      });

      const cleanedPaths = files.map((f) => getCleanPath(f, config));

      routeDeclCode = await generate_router_decl_code(
        cleanedPaths,
        config.routesDir || "routes",
      );

      await fs.writeFile(
        path.resolve(root, ".rumious", "__generated.rumious.ts"),
        `/** 
 * THIS FILE IS GENERATED BY RUMIOUS. 
 * DO NOT EDIT MANUALLY. 
 */


${routeDeclCode}`,
        "utf-8",
      );

      await fs.writeFile(
        path.resolve(root, ".rumious", "rumious.d.ts"),
        `/** 
 * THIS FILE IS GENERATED BY RUMIOUS. 
 * DO NOT EDIT MANUALLY. 
 */
declare module "@routes/*.page.ts" {
    import { Page } from "@rumious/router";
    export { Page };
}

declare module "@routes/*.layout.ts" {
    import { Layout } from "@rumious/router";
    export { Layout };
}
`,
        "utf-8",
      );

      if (server) {
        const mod = server.moduleGraph.getModuleById(
          RESOLVED_VIRTUAL_MODULE_ID,
        );
        if (mod) {
          server.moduleGraph.invalidateModule(mod);
        }
        server.ws.send({ type: "full-reload" });
      }
    } catch (e) {
      console.error("[Rumious Router] Failed to generate code:", e);
    }
  };
  return {
    name: "vite-plugin-rumious",
    enforce: "pre",

    config() {
      return {
        resolve: {
          alias: {
            "@routes": path.resolve(root, config.routesDir || "routes"),
          },
        },
      };
    },

    resolveId(id) {
      if (id === VIRTUAL_MODULE_ID) {
        return RESOLVED_VIRTUAL_MODULE_ID;
      }
    },

    load(id) {
      if (id === RESOLVED_VIRTUAL_MODULE_ID) {
        return routeDeclCode;
      }
    },

    async buildStart() {
      await refreshRouter();
    },

    configureServer(server) {
      server.watcher.add(ROUTES_DIR);

      const handleFileChange = async () => {
        await refreshRouter(server);
      };

      server.watcher.on("add", handleFileChange);
      server.watcher.on("change", handleFileChange);
      server.watcher.on("unlink", handleFileChange);
    },

    async transform(code: string, id: string) {
      if (id.endsWith(".tsx") || id.endsWith(".jsx")) {
        let compileOption = new CompileOption();
        compileOption.file_name = id;

        const result = await compile(code, compileOption);

        return {
          code: result.code,
          map: result.map,
        };
      }
    },
  };
}
